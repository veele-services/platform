/**
 * Central entity — drives planning, reporting, and invoicing.
 * Always linked to a customer; optionally to a specific object.
 *
 * scheduledDate / scheduledStart / scheduledEnd are stored as plain strings
 * (YYYY-MM-DD and HH:MM) to avoid timezone ambiguity in a multinational context.
 */
export const assignmentsTable = pgTable("assignments", {
  id:             uuid("id").primaryKey().defaultRandom(),
  tenantId:       uuid("tenant_id")
    .notNull()
    .references(() => tenantsTable.id, { onDelete: "cascade" }),
  /** Auto-generated by DB trigger trg_assignments_set_code — e.g. SCH-2026-0600001. */
  code:           varchar("code", { length: 20 }).notNull().unique().$defaultFn(() => ""),
  title:          varchar("title", { length: 255 }).notNull(),
  description:    text("description"),

  customerId:     uuid("customer_id")
    .notNull()
    .references(() => customersTable.id, { onDelete: "cascade" }),
  objectId:       uuid("object_id")
    .references(() => objectsTable.id, { onDelete: "set null" }),

  /** Current lifecycle status — see ASSIGNMENT_STATUS_TRANSITIONS for allowed moves. */
  status:         varchar("status", { length: 50 })
    .notNull()
    .default("requested"),
  priority:       varchar("priority", { length: 20 })
    .notNull()
    .default("normal"),

  /** YYYY-MM-DD — timezone-safe date string */
  scheduledDate:  varchar("scheduled_date", { length: 10 }),
  /** HH:MM */
  scheduledStart: varchar("scheduled_start", { length: 5 }),
  /** HH:MM */
  scheduledEnd:   varchar("scheduled_end", { length: 5 }),

  /** When the assigned personnel member first opened the work order. */
  seenAt:          timestamp("seen_at", { withTimezone: true }),
  /** Actual start timestamp captured from the personnel PWA. */
  actualStartedAt: timestamp("actual_started_at", { withTimezone: true }),
  /** Actual completion or not-completed timestamp captured from the personnel PWA. */
  actualCompletedAt: timestamp("actual_completed_at", { withTimezone: true }),
  /** Reason selected by personnel when the work order cannot be completed. */
  completionReason: varchar("completion_reason", { length: 160 }),
  /** Optional personnel notes for completed/not-completed closeout. */
  completionNotes: text("completion_notes"),
  /** Whether customer signature is required before the personnel PWA can complete the work order. */
  customerSignatureRequired: boolean("customer_signature_required").notNull().default(false),
  /** Data URL for the captured customer signature. */
  customerSignatureDataUrl: text("customer_signature_data_url"),
  /** Timestamp for the customer signature capture. */
  customerSignedAt: timestamp("customer_signed_at", { withTimezone: true }),

  /** Management-only internal notes. */
  notes:          text("notes"),

  /**
   * Optional free-text region requirement.
   * Must match personnel.region (case-insensitive, trimmed) when set.
   * NULL = no regional restriction.
   */
  requiredRegion: varchar("required_region", { length: 100 }),
  /** Explicit team size for smart planning. Defaults to one person. */
  requiredPersonnelCount: integer("required_personnel_count").notNull().default(1),

  isActive:       boolean("is_active").notNull().default(true),
  createdAt:      timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt:      timestamp("updated_at", { withTimezone: true }).notNull().defaultNow().$onUpdate(() => new Date()),
  /** Supabase Auth UUID of the staff member who created the record. */
  createdBy:      uuid("created_by"),
});

/** Many-to-many: personnel assigned to an assignment. */
export const assignmentPersonnelTable = pgTable(
  "assignment_personnel",
  {
    id:           uuid("id").primaryKey().defaultRandom(),
    assignmentId: uuid("assignment_id")
      .notNull()
      .references(() => assignmentsTable.id, { onDelete: "cascade" }),
    personnelId:  uuid("personnel_id")
      .notNull()
      .references(() => personnelTable.id, { onDelete: "cascade" }),
    /**
     * 'assigned'  — planned by the planner (default).
     * 'suggested' — self-applied by the field worker via the personeels-PWA.
     * 'declined'  — planner rejected the self-application.
     * Requires migration 016_assignment_personnel_status.sql to be run first.
     */
    status:       varchar("status", { length: 20 }).notNull().default("assigned"),
    assignedAt:   timestamp("assigned_at", { withTimezone: true }).notNull().defaultNow(),
    assignedBy:   uuid("assigned_by"),
  },
  (t) => [
    uniqueIndex("assignment_personnel_unique_idx").on(t.assignmentId, t.personnelId),
  ],
);

/** Task codes scoped to an assignment (the actual work to be performed). */
export const assignmentTasksTable = pgTable("assignment_tasks", {
  id:           uuid("id").primaryKey().defaultRandom(),
  assignmentId: uuid("assignment_id")
    .notNull()
    .references(() => assignmentsTable.id, { onDelete: "cascade" }),
  taskCodeId:   uuid("task_code_id")
    .references(() => taskCodesTable.id, { onDelete: "set null" }),
  tenantTaskCodeId: uuid("tenant_task_code_id")
    .references(() => tenantTaskCodesTable.id, { onDelete: "set null" }),
  tenantTaskCodePriceId: uuid("tenant_task_code_price_id")
    .references(() => tenantTaskCodePricesTable.id, { onDelete: "set null" }),
  /** Historical task-code snapshot used by quotes/invoices after prices change. */
  taskCodeCode: varchar("task_code_code", { length: 50 }),
  taskCodeName: varchar("task_code_name", { length: 200 }),
  taskCodePrice: numeric("task_code_price", { precision: 10, scale: 2 }),
  taskCodeInvoiceable: boolean("task_code_invoiceable"),
  notes:        text("notes"),
  sortOrder:    integer("sort_order").notNull().default(0),
  completedAt:  timestamp("completed_at", { withTimezone: true }),
  completedBy:  uuid("completed_by"),
});

